package domain.model;

/**
 * Файл: domain/model/PlayerType.java
 *
 * Назначение файла: перечисление типов участников текущей игры.
 * Появляется в задании 3, где игра может быть против другого человека (USER)
 * или против компьютера (AI).
 *
 * Используется:
 * - в GameSession (кто занимает крестики и кто нолики);
 * - в endpoint'ах создания/присоединения игры (с кем играем);
 * - в WebMapper при подготовке ответа клиенту.
 */
public enum PlayerType {

    /** Участник — реальный пользователь (идентифицируется его UUID). */
    USER,

    /** Участник — компьютер (алгоритм minimax), UUID у такой стороны отсутствует. */
    AI
}
